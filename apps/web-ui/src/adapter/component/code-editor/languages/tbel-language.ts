export const tbelLanguageConfiguration: languages.LanguageConfiguration = {
  autoClosingPairs: [
    { open: '{', close: '}' },
    { open: '[', close: ']' },
    { open: '(', close: ')' },
    { open: '"', close: '"', notIn: ['string', 'comment'] },
    { open: "'", close: "'", notIn: ['string', 'comment'] },
  ],
  brackets: [
    ['{', '}'],
    ['[', ']'],
    ['(', ')'],
  ],
  comments: { blockComment: ['/*', '*/'], lineComment: '//' },
  indentationRules: {
    decreaseIndentPattern: /^\s*[}\])]/,
    increaseIndentPattern: /^((?!\/\/).)*[({[]\s*(\/\/.*)?$/,
  },
  surroundingPairs: [
    { open: '{', close: '}' },
    { open: '[', close: ']' },
    { open: '(', close: ')' },
    { open: '"', close: '"' },
    { open: "'", close: "'" },
  ],
  wordPattern: /[$A-Z_a-z\u00A1-\uFFFF][$\w\u00A1-\uFFFF]*/g,
};

export const tbelMonarchLanguage: languages.IMonarchLanguage = {
  defaultToken: '',
  tokenPostfix: '.tbel',
  builtins: tbelBuiltins.map(({ name }) => name),
  keywords: tbelKeywords,
  constants: ['true', 'false', 'null', 'nil', 'empty'],
  types: [
    'boolean',
    'byte',
    'char',
    'double',
    'float',
    'int',
    'long',
    'short',
    'void',
    'Boolean',
    'Byte',
    'Character',
    'Double',
    'Float',
    'Integer',
    'Long',
    'Math',
    'Short',
    'String',
    'List',
    'Map',
    'Set',
    'Object',
  ],
  wordOperators: [
    'and',
    'or',
    'contains',
    'matches',
    'soundslike',
    'strsim',
    'convertable_to',
  ],
  escapes: /\\(?:[btnfr"'\\]|u[\da-fA-F]{4}|[0-7]{1,3})/,
  tokenizer: {
    root: [
      [/\s+/, 'white'],
      [/\/\*/, 'comment', '@comment'],
      [/\/\/.*$/, 'comment'],
      [/"/, 'string.quote', '@doubleQuoted'],
      [/'/, 'string.quote', '@singleQuoted'],
      [
        /[$A-Z_a-z\u00A1-\uFFFF][$\w\u00A1-\uFFFF]*/,
        {
          cases: {
            '@keywords': 'keyword',
            '@constants': 'constant',
            '@types': 'type',
            '@builtins': 'predefined',
            '@wordOperators': 'operator',
            '@default': 'identifier',
          },
        },
      ],
      [/0[xX][\da-fA-F]+[lLiI]?/, 'number.hex'],
      [/0[bB][01]+[lLiI]?/, 'number.binary'],
      [/0[oO][0-7]+[lLiI]?/, 'number.octal'],
      [/0[0-7]+[lL]?/, 'number.octal'],
      [/(?:\d+\.\d*|\.\d+|\d+)(?:[eE][+-]?\d+)?[dDfFlLiIbB]?/, 'number'],
      [/[{}()[\]]/, '@brackets'],
      [/[=><!~?:&|+*/^%.-]+/, 'operator'],
      [/[,;]/, 'delimiter'],
    ],
    comment: [
      [/[^/*]+/, 'comment'],
      [/\*\//, 'comment', '@pop'],
      [/[/*]/, 'comment'],
    ],
    doubleQuoted: [
      [/[^\\"]+/, 'string'],
      [/\\$/, 'string.escape'],
      [/@escapes/, 'string.escape'],
      [/\\./, 'string.escape.invalid'],
      [/"/, 'string.quote', '@pop'],
      [/$/, 'string.invalid', '@pop'],
    ],
    singleQuoted: [
      [/[^\\']+/, 'string'],
      [/\\$/, 'string.escape'],
      [/@escapes/, 'string.escape'],
      [/\\./, 'string.escape.invalid'],
      [/'/, 'string.quote', '@pop'],
      [/$/, 'string.invalid', '@pop'],
    ],
  },
};
